/**
 * generate-intro-paths.mjs
 * 
 * Reads Dancing Script Bold TTF and generates SVG path data
 * for "Hello", "Welcome", "To" and Imperial Script "Phūrai".
 * 
 * Run: node scripts/generate-intro-paths.mjs
 * Output: frontend/src/features/home/data/introPaths.js
 */

import opentype from 'opentype.js';
import { writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const FONT_SCRATCH = '/Users/phu/.gemini/antigravity-ide/scratch/fonts';
const OUT_FILE = join(__dirname, '../frontend/src/features/home/data/introPaths.js');

// Font size for path generation — determines viewBox scale
const FONT_SIZE = 120;

/**
 * Generate SVG path data + bounding box for a text string.
 * Returns { d, width, height, viewBox }
 */
function textToPath(font, text, fontSize) {
  // Render at x=10, y=fontSize+10 to give some padding
  const x = 10;
  const y = fontSize + 10;

  const path = font.getPath(text, x, y, fontSize);
  const bb = path.getBoundingBox();

  // Pad viewBox slightly
  const PAD = 12;
  const vx = Math.floor(bb.x1 - PAD);
  const vy = Math.floor(bb.y1 - PAD);
  const vw = Math.ceil(bb.x2 - bb.x1 + PAD * 2);
  const vh = Math.ceil(bb.y2 - bb.y1 + PAD * 2);

  return {
    d: path.toPathData(2),
    viewBox: `${vx} ${vy} ${vw} ${vh}`,
    width: vw,
    height: vh,
  };
}

async function main() {
  console.log('Loading Dancing Script Bold TTF...');
  const dsFont = opentype.loadSync(`${FONT_SCRATCH}/dancing-script-700.ttf`);
  console.log('Font loaded:', dsFont.names.fullName?.en || 'Dancing Script');

  const words = [
    { key: 'hello',   text: 'Hello',   font: dsFont },
    { key: 'welcome', text: 'Welcome', font: dsFont },
    { key: 'to',      text: 'To',      font: dsFont },
  ];

  const output = {};

  for (const { key, text, font } of words) {
    const result = textToPath(font, text, FONT_SIZE);
    output[key] = result;
    console.log(`${text}: viewBox="${result.viewBox}" path length=${result.d.length} chars`);
  }

  const js = `/**
 * AUTO-GENERATED by scripts/generate-intro-paths.mjs
 * Font: Dancing Script Bold 700 (Google Fonts)
 * Do NOT edit manually — re-run the script to regenerate.
 */

export const INTRO_PATHS = ${JSON.stringify(output, null, 2)};

export default INTRO_PATHS;
`;

  writeFileSync(OUT_FILE, js, 'utf8');
  console.log(`\nWritten to: ${OUT_FILE}`);
}

main().catch(err => {
  console.error('Error:', err.message);
  process.exit(1);
});
